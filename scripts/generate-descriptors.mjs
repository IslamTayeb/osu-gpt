/**
 * Regenerate the descriptor vocabulary from Mapperatorinator's dataset.
 *
 * Descriptors that aren't in the model's vocabulary silently map to an "unknown"
 * token rather than erroring, so a hand-maintained list drifts without anyone
 * noticing. Run via `npm run gen:descriptors` (wired into predev/prebuild).
 */
import fs from "node:fs";
import path from "node:path";

const repoDir = process.env.MAPPERATORINATOR_DIR
  ? path.resolve(process.env.MAPPERATORINATOR_DIR)
  : path.resolve(process.cwd(), "..", "Mapperatorinator");
const csvPath = path.join(repoDir, "datasets", "beatmap_descriptors.csv");
const outPath = path.resolve(process.cwd(), "lib", "generated", "descriptors.ts");

if (!fs.existsSync(csvPath)) {
  console.error(`[descriptors] ${csvPath} not found — keeping the existing generated file.`);
  process.exit(0);
}

const descriptors = [
  ...new Set(
    fs
      .readFileSync(csvPath, "utf8")
      .split("\n")
      .map((line) => line.slice(line.indexOf(",") + 1).trim())
      .filter((value) => value && value.includes(",") === false),
  ),
].sort((a, b) => a.localeCompare(b));

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  `// Generated by scripts/generate-descriptors.mjs — do not edit.\n` +
    `// Source: Mapperatorinator/datasets/beatmap_descriptors.csv\n\n` +
    `export const descriptorVocabulary = [\n` +
    descriptors.map((d) => `  ${JSON.stringify(d)},\n`).join("") +
    `] as const;\n\n` +
    `export type Descriptor = (typeof descriptorVocabulary)[number];\n\n` +
    `export function isDescriptor(value: string): value is Descriptor {\n` +
    `  return (descriptorVocabulary as readonly string[]).includes(value);\n` +
    `}\n`,
  "utf8",
);

console.log(`[descriptors] wrote ${descriptors.length} descriptors to lib/generated/descriptors.ts`);
